def alpha_from_theta(theta, alpha_min=0.1, alpha_max=0.7):
    """
    將風險偏好 θ 映射到 HotIndex 權重 α
    
    理論基礎：
    - 保守投資人(θ低)：更注重個人化適配，α 較低
    - 積極投資人(θ高)：更願意跟隨市場熱度，α 較高
    """
    return alpha_min + (alpha_max - alpha_min) * theta

